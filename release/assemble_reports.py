#!/usr/bin/env python3
"""Assemble the release's configs/ and reports/ trees exactly as the manifest paths describe, then tar them.

    configs/<domain>/<design_id>.json
    reports/<domain>/<design_id>/{csynth.xml, export_impl.xml, power_routed.rpt}       (sweeps)
    reports/modular/<domain>/<name>/{csynth.xml, <function>_csynth.xml, csynth.rpt}    (modularization suite)
    reports/fullmodel/<name>/{csynth.xml, csynth.rpt}                                 (full model-level designs)
    reports/catapult_vs_vitis/{catapult/<design>/rtl.rpt, vitis/<design>/csynth.xml}   (Catapult vs Vitis, 1,000 GEMM designs)

Inputs: manifest/designs/*.csv (which reports exist), the lean archives named in manifest/_common.py SOURCES,
checkpoints/r2/{csynth_modular_lean,fullmodel_csynth_lean,catapult_vs_vitis_lean}.tar.gz, and the generators (config text
is regenerated, not copied). The machine name in the tool reports (`| Host : ...` in power reports, `-- Generated by: user@host`
in Catapult reports) is replaced by `<host>` / `<user>@<host>`; nothing else in a report is changed.
Outputs under --out (default release/_bundle): `_tree/` (loose files, for checking) and one tarball per domain
(`configs_<domain>.tar.gz`, `reports_<domain>.tar.gz`, `reports_{modular,fullmodel,catapult_vs_vitis}.tar.gz`), each containing a SHA256SUMS of its
members (paths relative to the bundle root, so `sha256sum -c reports/<domain>/SHA256SUMS` works after extraction).
Finally every path in every manifest column is checked against the tree.

    python release/assemble_reports.py [--out DIR] [--domains gemm dnn llm] [--no-tar]
"""
import argparse
import csv
import hashlib
import os
import re
import shutil
import sys
import tarfile

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "manifest"))
from _common import DATA, DOMAINS, design_table, index_sources, load_generator, locate   # noqa: E402
from forgebench import paths   # noqa: E402

MODULAR_ARCHIVE = os.path.join("checkpoints", "r2", "csynth_modular_lean.tar.gz")
FULLMODEL_ARCHIVE = os.path.join("checkpoints", "r2", "fullmodel_csynth_lean.tar.gz")      # fullmodel/<name>/project_1/.../csynth.{xml,rpt}
CVV_ARCHIVE = os.path.join("checkpoints", "r2", "catapult_vs_vitis_lean.tar.gz")           # lean_catapult/<d>/rtl.rpt, lean_vitis/<d>/.../csynth.xml
HOST_LINES = [(re.compile(rb"^(\| Host\s*: )\S+", re.M), rb"\1<host>"),
              (re.compile(rb"^(-- Generated by:\s+)\S+", re.M), rb"\1<user>@<host>")]


def scrub(data):
    """Drop the machine name from a report; everything else is kept byte for byte."""
    for pat, sub in HOST_LINES:
        data = pat.sub(sub, data)
    return data


def write_member(tf, m, p):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "wb") as o:
        o.write(scrub(tf.extractfile(m).read()))


def read_manifest(domain):
    with open(os.path.join(REPO, "manifest", "designs", f"{domain}.csv"), newline="") as f:
        return {r["design_id"]: r for r in csv.DictReader(f)}


def extract(plan, tree):
    """plan: {archive_local: {member: dest_rel}} -> stream each archive once."""
    n = 0
    for local, wanted in plan.items():
        with tarfile.open(os.path.join(DATA, local), "r:gz") as tf:
            for m in tf:
                dest = wanted.get(m.name)
                if dest and m.isfile():
                    write_member(tf, m, os.path.join(tree, dest))
                    n += 1
    return n


def tar_dir(tree, subdir, out_path):
    """tar `tree/subdir` into out_path with an inner SHA256SUMS (member hashes) at the archive root."""
    root = os.path.join(tree, subdir)
    sums = []
    for dp, _, files in sorted(os.walk(root)):
        for fn in sorted(files):
            full = os.path.join(dp, fn)
            h = hashlib.sha256(open(full, "rb").read()).hexdigest()
            sums.append(f"{h}  {os.path.relpath(full, tree)}")
    sums_path = os.path.join(tree, f".SHA256SUMS.{subdir.replace('/', '_')}")
    with open(sums_path, "w") as f:
        f.write("\n".join(sums) + "\n")
    with tarfile.open(out_path, "w:gz") as tf:
        tf.add(root, arcname=subdir)
        tf.add(sums_path, arcname=f"{subdir}/SHA256SUMS")      # lands at reports/<domain>/SHA256SUMS after extraction
    os.remove(sums_path)
    return len(sums)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(REPO, "release", "_bundle"))
    ap.add_argument("--domains", nargs="*", default=DOMAINS)
    ap.add_argument("--no-tar", action="store_true")
    a = ap.parse_args()
    tree = os.path.join(a.out, "_tree")
    shutil.rmtree(tree, ignore_errors=True)
    os.makedirs(tree)

    index = index_sources()
    problems = []
    for domain in a.domains:
        manifest, table, gen = read_manifest(domain), design_table(domain), load_generator(domain)
        plan = {}
        for t in table:
            row = manifest[t["design_id"]]
            # configs: regenerated from the generator
            cp = os.path.join(tree, row["config_path"])
            os.makedirs(os.path.dirname(cp), exist_ok=True)
            with open(cp, "w") as f:
                f.write(gen.build_config_text(t["params"]))
            loc = locate(index, domain, t)
            for col, kind in (("csynth_report", "csynth"), ("impl_report", "impl"), ("impl_power_report", "power")):
                if row[col]:
                    if kind not in loc:
                        problems.append(f"{t['design_id']}: manifest lists {col} but no source report found")
                        continue
                    local, member = loc[kind]
                    plan.setdefault(local, {})[member] = row[col]
        n = extract(plan, tree)
        print(f"{domain}: {len(table)} configs, {n} report files extracted", flush=True)

    # modular suite
    if os.path.isfile(os.path.join(DATA, MODULAR_ARCHIVE)):
        with open(os.path.join(REPO, "manifest", "designs", "modular.csv"), newline="") as f:
            mod = {r["design_id"]: r for r in csv.DictReader(f) if r["csynth"] == "YES"}
        n = 0
        with tarfile.open(os.path.join(DATA, MODULAR_ARCHIVE), "r:gz") as tf:
            for m in tf:
                parts = m.name.split("/")           # modular/<domain>/<name>/project_1/solution1/syn/report/<file>
                dom = {v: k for k, v in paths.RECORDED.items()}.get(parts[1], parts[1]) if len(parts) > 1 else ""   # archive says conv
                if m.isfile() and len(parts) == 8 and parts[3:7] == ["project_1", "solution1", "syn", "report"] \
                        and f"modular/{dom}/{parts[2]}" in mod:
                    write_member(tf, m, os.path.join(tree, "reports", "modular", dom, parts[2], parts[7]))
                    n += 1
        print(f"modular: {len(mod)} designs, {n} report files extracted")
    else:
        problems.append(f"{MODULAR_ARCHIVE} not found")

    # full model-level designs: csynth.xml + csynth.rpt of the designs registered in manifest/designs/fullmodel.csv
    with open(os.path.join(REPO, "manifest", "designs", "fullmodel.csv"), newline="") as f:
        full = {r["name"] for r in csv.DictReader(f) if r["csynth"] == "YES"}
    if os.path.isfile(os.path.join(DATA, FULLMODEL_ARCHIVE)):
        n = 0
        with tarfile.open(os.path.join(DATA, FULLMODEL_ARCHIVE), "r:gz") as tf:
            for m in tf:
                parts = m.name.split("/")           # fullmodel/<name>/project_1/solution1/syn/report/csynth.{xml,rpt}
                if m.isfile() and len(parts) == 7 and parts[1] in full and parts[6] in ("csynth.xml", "csynth.rpt"):
                    write_member(tf, m, os.path.join(tree, "reports", "fullmodel", parts[1], parts[6]))
                    n += 1
        print(f"fullmodel: {len(full)} designs, {n} report files extracted")
    else:
        problems.append(f"{FULLMODEL_ARCHIVE} not found")

    # Catapult vs Vitis: the 1,000 sampled GEMM designs of results/catapult_vs_vitis/sample.csv, both tools
    with open(os.path.join(REPO, "results", "catapult_vs_vitis", "sample.csv"), newline="") as f:
        sample = {r["design"] for r in csv.DictReader(f)}
    if os.path.isfile(os.path.join(DATA, CVV_ARCHIVE)):
        got = {"catapult": set(), "vitis": set()}
        with tarfile.open(os.path.join(DATA, CVV_ARCHIVE), "r:gz") as tf:
            for m in tf:
                parts = m.name.split("/")
                tool = {"lean_catapult": "catapult", "lean_vitis": "vitis"}.get(parts[0])
                if m.isfile() and tool and len(parts) > 2 and parts[1] in sample and parts[-1] in ("rtl.rpt", "csynth.xml"):
                    write_member(tf, m, os.path.join(tree, "reports", "catapult_vs_vitis", tool, parts[1], parts[-1]))
                    got[tool].add(parts[1])
        for tool, names in got.items():
            if names != sample:
                problems.append(f"catapult_vs_vitis/{tool}: {len(sample - names)} sampled designs without a report")
        print(f"catapult_vs_vitis: {len(got['catapult'])} Catapult + {len(got['vitis'])} Vitis reports extracted")
    else:
        problems.append(f"{CVV_ARCHIVE} not found")

    # every path the manifests claim must exist in the tree
    for domain in a.domains + ["modular", "fullmodel"]:
        cols = ("config_path", "csynth_report", "impl_report", "impl_power_report") if domain in DOMAINS else ("csynth_report",)
        with open(os.path.join(REPO, "manifest", "designs", f"{domain}.csv"), newline="") as f:
            for r in csv.DictReader(f):
                for col in cols:
                    if r[col] and not os.path.isfile(os.path.join(tree, r[col])):
                        problems.append(f"{r['design_id']}: {col} {r[col]} missing from the assembled tree")
    if problems:
        print(f"{len(problems)} problems, e.g.:\n  " + "\n  ".join(problems[:8]))
        sys.exit(1)
    print("manifest paths: all present in the assembled tree")

    if not a.no_tar:
        for domain in a.domains:
            for kind in ("configs", "reports"):
                if os.path.isdir(os.path.join(tree, kind, domain)):
                    n = tar_dir(tree, f"{kind}/{domain}", os.path.join(a.out, f"{kind}_{domain}.tar.gz"))
                    print(f"{kind}_{domain}.tar.gz: {n} files, {os.path.getsize(os.path.join(a.out, f'{kind}_{domain}.tar.gz')) / 1e6:.0f} MB")
        for suite in ("modular", "fullmodel", "catapult_vs_vitis"):
            if os.path.isdir(os.path.join(tree, "reports", suite)):
                n = tar_dir(tree, f"reports/{suite}", os.path.join(a.out, f"reports_{suite}.tar.gz"))
                print(f"reports_{suite}.tar.gz: {n} files")


if __name__ == "__main__":
    main()
