"""Stage tables: which designs passed which tool stage. From manifest/ and results/ only (no EDA tools).

  tab:synth_summary  ML sweep synthesis and implementation outcome per domain  -> out/tables/synth_summary.{csv,tex}
  tab:status         stages passed by every design set of the paper            -> out/tables/status_summary.{csv,tex}

    python -m paper_artifacts.stage_tables

Synthesis: a design passes if its csynth report exists and its estimate fits the ZCU102 (manifest `over_capacity`); over-capacity
designs still completed csynth. Implementation: over the seeded sample (manifest/ml_sweep/<domain>_impl_selection.csv); a failure
is "over capacity" if Vivado rejected it for resources, "timeout" if it timed out, else "error" (manifest/ml_sweep/impl_failures.csv).
"""
import csv
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "paper_artifacts", "out", "tables")
DOMAINS = [("gemm", "GEMM"), ("dnn", "DNN"), ("llm", "LLM")]


def read(*parts):
    with open(os.path.join(REPO, *parts), newline="") as f:
        return list(csv.DictReader(f))


def n(x):
    return f"{x:,}"


def pct(k, total):
    p = 100 * k / total
    return f"{p:.0f}" if p == round(p) else f"{p:.1f}"


def kind(reason):
    r = reason.lower()
    return "over_cap" if "over capacity" in r else "timeout" if "timeout" in r else "error"


def within(rows):
    return all(r["status"] == "ok" and r["n_trials"] == r["trials_within_bound"] for r in rows)


# ----------------------------------------------------------------------------- tab:synth_summary
def synth_summary():
    out = []
    for d, label in DOMAINS:
        m = read("manifest", "designs", f"{d}.csv")
        fails = {r["design_id"]: kind(r["impl_fail_reason"]) for r in read("manifest", "ml_sweep", "impl_failures.csv")
                 if r["domain"] == d}
        sel = len(read("manifest", "ml_sweep", f"{d}_impl_selection.csv"))
        s = {"error": sum(r["csynth"] == "FAIL" for r in m), "timeout": 0,
             "over_cap": sum(r["csynth"] == "YES" and r["over_capacity"] == "YES" for r in m)}
        s["pass"] = sum(r["csynth"] == "YES" and r["over_capacity"] != "YES" for r in m)
        i = {k: sum(v == k for v in fails.values()) for k in ("error", "timeout", "over_cap")}
        i["pass"] = sum(r["impl"] == "YES" for r in m)
        assert i["pass"] + len(fails) == sel, f"{d}: {i['pass']} implemented + {len(fails)} failed != {sel} selected"
        out.append({"domain": label, "designs": len(m), "impl_selected": sel,
                    **{f"synth_{k}": v for k, v in s.items()}, **{f"impl_{k}": v for k, v in i.items()}})
    keys = ("error", "timeout", "over_cap", "pass")
    tex = ["% generated by paper_artifacts/stage_tables.py from manifest/designs/{gemm,dnn,llm}.csv and manifest/ml_sweep/",
           r"\begin{tabular}{ll cccc cccc}", r"\toprule",
           r"    \textbf{Class} & \textbf{Testcases} & \multicolumn{4}{c}{\textbf{Synthesis}} & \multicolumn{4}{c}{\textbf{Implementation}} \\",
           r"    \cmidrule(lr){3-6}", r"    \cmidrule(lr){7-10}",
           r"    & & Error & Timeout & Over Cap. & Pass", r"      & Error & Timeout & Over Cap. & Pass \\", r"    \midrule"]
    for r in out:
        cells = [f"{n(r['synth_' + k])} ({pct(r['synth_' + k], r['designs'])}\\%)" for k in keys]
        cells += [f"{n(r['impl_' + k])} ({pct(r['impl_' + k], r['impl_selected'])}\\%)" for k in keys]
        tex.append(f"    {r['domain']} & {n(r['designs'])} & " + " & ".join(cells) + r" \\")
    tex += [r"    \bottomrule", r"\end{tabular}"]
    return out, tex


# ----------------------------------------------------------------------------- tab:status
def frac(k, total):
    return f"{n(k)}/{n(total)}"


def status_summary():
    S = {"verification": r"\S\ref{sec:verification}", "portability": r"\S\ref{sec:portability}",
         "full": r"\S\ref{sec:full_ml_models}", "synth": r"\S\ref{sec:synth_ppa}", "impl": r"\S\ref{sec:impl_ppa}",
         "catapult": r"\S\ref{sec:catapult_synth}", "modular": r"\S\ref{sec:modular_benchmark}"}
    rows = []

    def add(group, name, tool, designs, csim=None, cosim=None, csynth=None, impl=None):
        rows.append({"group": group, "design_set": name, "tool": tool, "designs": designs,
                     **{k: v for k, v in (("csim", csim), ("cosim", cosim), ("csynth", csynth), ("impl", impl))}})

    # operator variants (Vitis): CSIM faithful at +-1 in <32,10> and float; CO-SIM RTL == C; co-simulation implies csynth
    ops = [r for r in read("manifest", "verification", "operators.csv") if r["experiment"] == "pm1"]
    variants = sorted({r["design"] for r in ops})
    csim_ok = [v for v in variants if all(within([r]) for r in ops if r["design"] == v and r["column"] in ("C_32_10", "D_float"))]
    cos = read("manifest", "verification", "cosim.csv")
    cos_ok = [v for v in variants if sum(r["design"] == v and r["cosim_status"] == "ok" and r["cosim_c_vs_rtl_mismatches"] == "0"
                                         for r in cos) == 2]
    add(0, "All Operator Variants", "Vitis", len(variants), (frac(len(csim_ok), len(variants)), "verification"),
        (frac(len(cos_ok), len(variants)), "verification"), (frac(len(cos_ok), len(variants)), None))
    cat = read("manifest", "verification", "catapult.csv")
    cat_v = sorted({r["design"] for r in cat})
    cat_ok = [v for v in cat_v if all(r["csim_status"] == "ok" and r["csim_n"] == r["csim_within"] for r in cat if r["design"] == v)]
    add(0, "GEMM Operator Variants", "Catapult", len(cat_v), (frac(len(cat_ok), len(cat_v)), "portability"))

    # full model-level designs: CSIM = every seed of the design's runs PASS (fixed-point bit-exact and FP64 within 5%)
    fm = read("manifest", "designs", "fullmodel.csv")
    runs = read("manifest", "verification", "fullmodel.csv")
    for label, pick in (("ResNet-18 to -152", lambda r: r["model"].startswith("ResNet")),
                        ("Llama-3-8B, prefill--decode", lambda r: r["model"].startswith("Llama"))):
        ds = [r for r in fm if pick(r)]
        ok = [r for r in ds if all(x["verdict"] == "PASS" for x in runs if x["group"] == os.path.basename(r["csim_runs"]))
              and int(r["csim_seeds"]) > 0]
        add(1, label, "Vitis", len(ds), (frac(len(ok), len(ds)), "full"), None,
            (frac(sum(r["csynth"] == "YES" for r in ds), len(ds)), "full"))

    # ML sweeps: csynth completed (over-capacity estimates included); implementation over the seeded sample
    for d, label in DOMAINS:
        m = read("manifest", "designs", f"{d}.csv")
        sel = len(read("manifest", "ml_sweep", f"{d}_impl_selection.csv"))
        add(2, f"{label} sweep", "Vitis", len(m), None, None, (frac(sum(r["csynth"] == "YES" for r in m), len(m)), "synth"),
            (frac(sum(r["impl"] == "YES" for r in m), sel), "impl"))
    st = read("results", "catapult_vs_vitis", "status_catapult.csv")
    add(2, "Sampled GEMM sweep", "Catapult", len(st), None, None, (frac(sum(r["status"] == "ok" for r in st), len(st)), "catapult"))

    # modularization: the 26 programs and the 12 modularized designs (each checked against every one of its programs)
    mod = read("manifest", "designs", "modular.csv")
    progs = read("manifest", "verification", "table7_programs.csv")
    merged = read("manifest", "verification", "table7_modularized.csv")
    p = [r for r in mod if r["role"] == "program"]
    md = [r for r in mod if r["role"] == "modularized_design"]
    md_ok = {r["merged_design"] for r in merged} - {r["merged_design"] for r in merged if not within([r])}
    add(3, "Modularization programs", "Vitis", len(p), (frac(sum(within([r]) for r in progs), len(p)), "modular"), None,
        (frac(sum(r["csynth"] == "YES" for r in p), len(p)), "modular"))
    add(3, "Modularized designs", "Vitis", len(md), (frac(len(md_ok), len(md)), "modular"), None,
        (frac(sum(r["csynth"] == "YES" for r in md), len(md)), "modular"))

    def cell(v):
        return "--" if v is None else v[0] + (f" {S[v[1]]}" if v[1] else "")

    tex = ["% generated by paper_artifacts/stage_tables.py from manifest/ and results/catapult_vs_vitis/",
           r"\begin{tabular}{lllllll}", r"\toprule",
           r"\textbf{Design Set} & \textbf{Tool} & \textbf{Designs} & \textbf{CSIM} & \textbf{CO-SIM} & \textbf{C-Synth.} & \textbf{Impl.} \\",
           r"\midrule"]
    for k, r in enumerate(rows):
        if k and r["group"] != rows[k - 1]["group"]:
            tex.append(r"\midrule")
        tex.append(" & ".join([r["design_set"], r["tool"], n(r["designs"])] + [cell(r[c]) for c in ("csim", "cosim", "csynth", "impl")])
                   + r" \\")
    tex += [r"\bottomrule", r"\end{tabular}"]
    flat = [{"design_set": r["design_set"], "tool": r["tool"], "designs": r["designs"],
             **{c: (r[c][0] if r[c] else "") for c in ("csim", "cosim", "csynth", "impl")}} for r in rows]
    return flat, tex


def write(name, recs, tex):
    with open(os.path.join(OUT, name + ".csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(recs[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(recs)
    with open(os.path.join(OUT, name + ".tex"), "w") as f:
        f.write("\n".join(tex) + "\n")
    print(f"wrote {os.path.relpath(os.path.join(OUT, name), REPO)}.{{csv,tex}} ({len(recs)} rows)")


def main():
    os.makedirs(OUT, exist_ok=True)
    write("synth_summary", *synth_summary())
    write("status_summary", *status_summary())


if __name__ == "__main__":
    main()
